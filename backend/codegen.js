async function sendText(to, body) {
  const res = await fetch(META.graphBase + "/" + META.phoneNumberId + "/messages", {
    method: "POST",
    headers: { Authorization: "Bearer " + META.accessToken, "Content-Type": "application/json" },
    body: JSON.stringify({ messaging_product: "whatsapp", to, type: "text", text: { body } }),
  });
  if (!res.ok) console.error("Graph API error", res.status, await res.text().catch(() => ""));
}

// ---- Server ----
const app = express();
app.use(express.json());

// Webhook verification handshake
app.get("/webhook", (req, res) => {
  if (req.query["hub.mode"] === "subscribe" && req.query["hub.verify_token"] === META.verifyToken) {
    return res.status(200).send(req.query["hub.challenge"]);
  }
  res.sendStatus(403);
});

