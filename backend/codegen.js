// Code export: assembles a standalone single-file server.js for a
// bot, from fixed templates + the flow serialized as JSON.
// Purely deterministic string assembly — no AI.
// ============================================================

function generateTwilio(flow) {
  const creds = flow.twilio || {};
  const flowJson = JSON.stringify(
    { nodes: flow.nodes.map(({ id, type, config }) => ({ id, type, config })), edges: flow.edges },
    null,
    2
  );

  return `// ============================================================
// ${flow.name || "FlowBot"} — standalone WhatsApp bot server
// Generated by FlowBot from your flowchart (template-assembled, no AI).
// Setup:  npm install express   →   node server.js
// Webhook: POST http://<your-host>:3000/whatsapp  (set in Twilio Sandbox)
// ============================================================

const express = require("express");

const TWILIO = {
  accountSid: process.env.TWILIO_SID || "${creds.sid || "YOUR_TWILIO_ACCOUNT_SID"}",
  authToken:  process.env.TWILIO_TOKEN || "${creds.token ? "SET_VIA_ENV_VAR" : "YOUR_TWILIO_AUTH_TOKEN"}",
  whatsappNumber: "${creds.number || "whatsapp:+14155238886"}",
};

// ---- Your flowchart, serialized ----
const FLOW = ${flowJson};

// ---- Pre-embedded engine (one handler per feature block) ----
const interp = (m, v) => m.replace(/\\{(\\w+)\\}/g, (_, k) => v[k] ?? k);
const byId = Object.fromEntries(FLOW.nodes.map(n => [n.id, n]));
const next = (id, port) => {
  const e = FLOW.edges.find(x => x.from === id && x.fromPort === port);
  return e ? byId[e.to] : null;
};
const sessions = {}; // per-phone: { state, vars }

function handleMessage(text, s) {
  const out = [];
  function runFrom(node) {
    let cur = node, guard = 0;
    while (cur && guard++ < 50) {
      const c = cur.config;
      switch (cur.type) {
        case "welcome": out.push(c.message); cur = next(cur.id, 0); break;
        case "menu":
          out.push(c.prompt + "\\n\\n" + c.options.map((o,i) => (i+1) + ". " + o).join("\\n") + "\\n\\nReply with a number.");
          s.state = cur.id; return;
        case "faq":
          out.push("Ask me anything — keywords: " + c.pairs.map(p => p.k).join(", ") + ". Type 0 when done.");
          s.state = cur.id; return;
        case "collect": out.push(c.question); s.state = cur.id; return;
        case "goodbye": out.push(interp(c.message, s.vars)); s.state = null; s.vars = {}; return;
        default: cur = next(cur.id, 0);
      }
    }
    if (!cur) s.state = null;
  }

  const t = String(text || "").trim();
  if (!s.state) {
    const start = FLOW.nodes.find(n => n.type === "welcome");
    if (!start) { out.push("This bot has no Welcome block."); return out; }
    runFrom(start); return out;
  }
  const cur = byId[s.state];
  if (!cur) { s.state = null; return handleMessage(text, s); }

  if (cur.type === "menu") {
    const i = parseInt(t, 10) - 1;
    if (Number.isInteger(i) && i >= 0 && i < cur.config.options.length) {
      const nx = next(cur.id, i);
      if (nx) runFrom(nx); else { s.state = null; out.push("Done! Say hi to start again."); }
    } else out.push("Please reply with a number between 1 and " + cur.config.options.length + ".");
    return out;
  }
  if (cur.type === "faq") {
    if (t === "0") {
      const nx = next(cur.id, 0);
      if (nx) runFrom(nx); else { s.state = null; out.push("Done! Say hi to start again."); }
      return out;
    }
    const hit = cur.config.pairs.find(p => t.toLowerCase().includes(p.k.toLowerCase()));
    out.push(hit ? hit.a : "No answer for that yet. Try another keyword or type 0.");
    return out;
  }
  if (cur.type === "collect") {
    s.vars[cur.config.field] = t;
    out.push("Got it.");
    const nx = next(cur.id, 0);
    if (nx) runFrom(nx); else s.state = null;
    return out;
  }
  s.state = null;
  return out;
}

// ---- TwiML helpers (hand-rolled, so the only dependency is express) ----
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const twiml = (msgs) =>
  '<?xml version="1.0" encoding="UTF-8"?><Response>' +
  msgs.map(m => "<Message>" + esc(m) + "</Message>").join("") +
  "</Response>";

// ---- Server ----
const app = express();
app.use(express.urlencoded({ extended: false }));

app.post("/whatsapp", (req, res) => {
  const from = req.body.From || "unknown";
  const body = req.body.Body || "";
  const s = sessions[from] || (sessions[from] = { state: null, vars: {} });
  res.type("text/xml").send(twiml(handleMessage(body, s)));
});

app.get("/", (_req, res) => res.send("${(flow.name || "FlowBot").replace(/"/g, "")} is running. Webhook: POST /whatsapp"));

app.listen(3000, () => console.log("Bot listening on :3000 — webhook: POST /whatsapp"));
`;
}

