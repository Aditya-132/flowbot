function generateReadme(flow, info) {
  const name = flow.name || "FlowBot";
  return `# ${name}

Standalone WhatsApp bot generated by FlowBot from your flowchart.
Deterministic runtime — no AI, no external services beyond your WhatsApp provider (${info.label}).

## Quick start

\`\`\`bash
npm install
cp .env.example .env   # fill in your ${info.label} credentials
npm run start:env      # bot listens on :3000 — webhook: ${info.webhook}
\`\`\`

(Credentials you entered in FlowBot are also baked into \`server.js\` as fallbacks,
so plain \`npm start\` works too.)

## Connect it to WhatsApp (${info.label})

${info.steps.map((s, i) => `${i + 1}. ${s}`).join("\n")}

## Files

- \`server.js\` — the complete bot: your flow (as JSON), the FlowBot engine, and the ${info.label} webhook wiring.
- \`.env.example\` — credentials template. Copy to \`.env\`; \`npm start\` loads it automatically.
- \`package.json\` — one dependency (express).

## Editing the bot

The conversation lives in the \`FLOW\` object at the top of \`server.js\` — nodes are blocks,
edges are the wires between them. For bigger changes, edit the flow visually in FlowBot
and download a fresh ZIP.
`;
}

function generateProject(flow) {
  const provider = PROVIDER_INFO[flow.provider] ? flow.provider : "twilio";
  const info = PROVIDER_INFO[provider];
  const pkg = {
    name: (flow.name || "flowbot-bot").toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "") || "flowbot-bot",
    version: "1.0.0",
    private: true,
    description: `WhatsApp bot generated by FlowBot (${info.label})`,
    main: "server.js",
    scripts: { start: "node server.js", "start:env": "node --env-file=.env server.js" },
    engines: { node: ">=20" },
    dependencies: { express: "^4.21.2" },
  };
  return [
    { name: "server.js", data: generateStandalone(flow) },
    { name: "package.json", data: JSON.stringify(pkg, null, 2) + "\n" },
    { name: "README.md", data: generateReadme(flow, info) },
    { name: ".env.example", data: info.env.join("\n") + "\n" },
  ];
}

